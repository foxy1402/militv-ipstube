#!/usr/bin/env python3
"""Generate an anti-aliased 4-bit-alpha bitmap font atlas header from a TTF.

Usage:
    python3 militv-font-atlas-gen.py RobotoMono.ttf 20 roboto_mono_20.h

Why this exists: MiliTV's MiniTFT renders a 5x7 bitmap font scaled in whole
blocks, so every glyph edge is a hard pixel step. Hito looks smooth because
Slint rasterises a *vector* font (Roboto Mono) with anti-aliasing. This script
does that rasterisation offline, once, with PIL: each glyph is rendered at the
target pixel size into a grayscale image, then quantised to 4-bit alpha and
packed 2 pixels/byte. The firmware then just alpha-blends the atlas into its
PSRAM framebuffer (see MiniTFT::textAA in the patch) - no TTF parser on the
device, no extra RAM at runtime beyond the atlas itself in flash.

Output header format:
    RM20_FIRST / RM20_COUNT / RM20_CAP_TOP: first char, glyph count, yoff of 'A'
    struct Rm20Glyph { adv, w, h, xoff, yoff, off }:
        adv  - horizontal advance in px (monospace: constant, kept per-glyph)
        w,h  - ink-box size in px
        xoff - ink left edge relative to the glyph origin (left side bearing)
        yoff - ink top edge relative to the font ascender line
        off  - byte offset of the glyph's packed nibbles in kRm20Bitmap
    kRm20Bitmap: 4-bit alpha, row-major, high nibble first, 0=transparent.

Rendering rule (firmware side): glyph top = y_top + (g.yoff - RM20_CAP_TOP),
glyph left = x + g.xoff, pixel alpha = nibble * 17, blend over framebuffer.
y_top is the top of the cap-height band, i.e. where the ink top of 'A' sits -
so a call site that used text(x, y, s, color, 2) keeps the same x and y.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

def main():
    ttf_path, px, out_path = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    prefix = f"RM{px}"
    font = ImageFont.truetype(ttf_path, px)
    ascent, descent = font.getmetrics()
    # Printable ASCII 32..90: space, punctuation, digits, A-Z. MiliTV's
    # text() uppercases lowercase anyway, so no lowercase glyphs needed.
    charset = [chr(c) for c in range(32, 91)]
    glyphs = []
    bitmap = bytearray()
    for ch in charset:
        # Anchor 'la' (left, ascender): bbox is relative to the ascender line.
        l, t, r, b = ImageDraw.Draw(Image.new("L", (1, 1))).textbbox((0, 0), ch, font=font, anchor="la")
        w, h = r - l, b - t
        adv = int(round(font.getlength(ch)))
        if w <= 0 or h <= 0:
            glyphs.append((adv, 0, 0, 0, t, len(bitmap)))
            continue
        im = Image.new("L", (w + 2, h + 2), 0)
        d = ImageDraw.Draw(im)
        d.text((1 - l, 1 - t), ch, font=font, fill=255, anchor="la")
        pxdata = list(im.getdata())
        # Crop the 1px guard border back off; keep the ink box only.
        ink = [pxdata[(yy + 1) * (w + 2) + (xx + 1)] for yy in range(h) for xx in range(w)]
        off = len(bitmap)
        for i in range(0, len(ink), 2):
            hi = ink[i] >> 4
            lo = (ink[i + 1] >> 4) if i + 1 < len(ink) else 0
            bitmap.append((hi << 4) | lo)
        glyphs.append((adv, w, h, l, t, off))
    cap_top = glyphs[ord("A") - 32][4]
    name = prefix
    with open(out_path, "w") as f:
        f.write(f"// Generated by militv-font-atlas-gen.py from {ttf_path} at {px}px.\n")
        f.write(f"// Roboto Mono, SIL Open Font License 1.1 - see the OFL notice in the font.\n")
        f.write("// Do not edit by hand; regenerate with the script.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define {name}_FIRST 32\n#define {name}_COUNT {len(charset)}\n")
        f.write(f"#define {name}_CAP_TOP {cap_top}\n")
        f.write(f"#define {name}_ASCENT {ascent}\n\n")
        f.write(f"struct {name}Glyph {{ uint8_t adv, w, h; int8_t xoff, yoff; uint16_t off; }};\n")
        f.write(f"static const {name}Glyph k{name}Glyphs[{name}_COUNT] = {{\n")
        for g in glyphs:
            f.write("  {%d, %d, %d, %d, %d, %d},\n" % g)
        f.write("};\n\n")
        f.write(f"static const uint8_t k{name}Bitmap[{len(bitmap)}] = {{\n")
        for i in range(0, len(bitmap), 20):
            f.write("  " + ",".join(f"0x{b:02x}" for b in bitmap[i:i + 20]) + ",\n")
        f.write("};\n")
    print(f"{out_path}: {len(glyphs)} glyphs, {len(bitmap)} bitmap bytes, cap_top={cap_top}, ascent={ascent}")

if __name__ == "__main__":
    main()
